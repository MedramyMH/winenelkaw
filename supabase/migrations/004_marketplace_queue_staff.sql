-- Add staff members only to businesses the caller manages. Availability is configurable per weekday.
create or replace function public.add_business_staff(p_business_id bigint,p_display_name text,p_weekdays smallint[] default array[1,2,3,4,5,6],p_starts_at time default '09:00',p_ends_at time default '18:00')
returns bigint language plpgsql security definer set search_path='' as $$
declare v_staff_id bigint; v_day smallint;
begin
 if auth.uid() is null then raise exception 'Authentication required'; end if;
 if not (exists(select 1 from public.businesses b where b.id=p_business_id and b.owner_id=auth.uid()) or public.is_business_member(p_business_id) or public.is_admin()) then raise exception 'Business access denied'; end if;
 if length(trim(coalesce(p_display_name,'')))<2 or p_starts_at>=p_ends_at then raise exception 'Invalid staff details or schedule'; end if;
 insert into public.staff_profiles(business_id,display_name,is_active) values(p_business_id,trim(p_display_name),true) returning id into v_staff_id;
 foreach v_day in array p_weekdays loop
  if v_day between 0 and 6 then insert into public.staff_availability(staff_id,weekday,starts_at,ends_at) values(v_staff_id,v_day,p_starts_at,p_ends_at); end if;
 end loop;
 return v_staff_id;
end; $$;
revoke all on function public.add_business_staff(bigint,text,smallint[],time,time) from public;
grant execute on function public.add_business_staff(bigint,text,smallint[],time,time) to authenticated;

-- Scan 1: customer arrives. Scan 2: service is finished. The salon's authorized team
-- can only change bookings for their business. QR tokens are unguessable and unique.
create or replace function public.scan_booking_qr(p_qr_token text,p_action text)
returns table(booking_id bigint,booking_reference text,queue_status text,estimated_wait_minutes integer,estimated_start_at timestamptz)
language plpgsql security definer set search_path='' as $$
declare v_booking public.bookings%rowtype; v_now timestamptz:=now(); v_active_count integer; v_wait integer;
begin
 if auth.uid() is null then raise exception 'Authentication required'; end if;
 if p_action not in ('check_in','start_service','complete') then raise exception 'Invalid scan action'; end if;
 select b.* into v_booking from public.bookings b where b.qr_token=p_qr_token for update;
 if not found then raise exception 'Invalid QR code'; end if;
 if not (exists(select 1 from public.businesses bu where bu.id=v_booking.business_id and bu.owner_id=auth.uid()) or public.is_business_member(v_booking.business_id) or public.is_admin()) then raise exception 'Only the salon team can scan the queue QR'; end if;
 if v_booking.booking_date < (v_now at time zone v_booking.timezone)::date then raise exception 'This appointment is in the past'; end if;
 if p_action='check_in' then
  if v_booking.status not in ('confirmed','pending') or v_booking.queue_status<>'scheduled' then raise exception 'Booking cannot check in in its current state'; end if;
  select count(*)::int into v_active_count from public.bookings b where b.business_id=v_booking.business_id and b.booking_date=v_booking.booking_date and b.queue_status='in_service';
  select coalesce(sum(greatest(5,extract(epoch from (b.end_time-b.start_time))/60)::int),0)::int into v_wait from public.bookings b where b.business_id=v_booking.business_id and b.booking_date=v_booking.booking_date and b.queue_status='checked_in' and (b.start_time,b.id)<(v_booking.start_time,v_booking.id);
  update public.bookings set queue_status='checked_in',checked_in_at=v_now,estimated_wait_minutes=v_wait,estimated_start_at=v_now+make_interval(mins=>v_wait),updated_at=v_now where id=v_booking.id;
 elsif p_action='start_service' then
  if v_booking.queue_status<>'checked_in' then raise exception 'Customer must check in before starting'; end if;
  update public.bookings set queue_status='in_service',service_started_at=v_now,estimated_wait_minutes=0,estimated_start_at=v_now,updated_at=v_now where id=v_booking.id;
 else
  if v_booking.queue_status<>'in_service' then raise exception 'Service must be started before completion'; end if;
  update public.bookings set queue_status='completed',service_completed_at=v_now,status='completed',updated_at=v_now where id=v_booking.id;
  if v_booking.status <> 'completed' then
   insert into public.booking_status_history(booking_id,changed_by,old_status,new_status,note) values(v_booking.id,auth.uid(),v_booking.status,'completed','Completed through salon QR queue scan');
  end if;
 end if;
 -- Recompute the waiting estimate after every scan so delays propagate to the queue.
 update public.bookings q set
   estimated_wait_minutes = greatest(0,
     coalesce((select greatest(0,ceil(extract(epoch from (a.end_time - (v_now at time zone a.timezone)::time))/60)::int)
       from public.bookings a where a.business_id=q.business_id and a.booking_date=q.booking_date and a.queue_status='in_service' limit 1),0)
     + coalesce((select sum(greatest(5,ceil(extract(epoch from (p.end_time-p.start_time))/60)::int))::int
       from public.bookings p where p.business_id=q.business_id and p.booking_date=q.booking_date and p.queue_status='checked_in'
       and (p.start_time,p.id)<(q.start_time,q.id)),0)),
   estimated_start_at = v_now + make_interval(mins => greatest(0,
     coalesce((select greatest(0,ceil(extract(epoch from (a.end_time - (v_now at time zone a.timezone)::time))/60)::int)
       from public.bookings a where a.business_id=q.business_id and a.booking_date=q.booking_date and a.queue_status='in_service' limit 1),0)
     + coalesce((select sum(greatest(5,ceil(extract(epoch from (p.end_time-p.start_time))/60)::int))::int
       from public.bookings p where p.business_id=q.business_id and p.booking_date=q.booking_date and p.queue_status='checked_in'
       and (p.start_time,p.id)<(q.start_time,q.id)),0)))
 where q.business_id=v_booking.business_id and q.booking_date=v_booking.booking_date and q.queue_status='checked_in';
 return query select b.id,b.booking_reference,b.queue_status,b.estimated_wait_minutes,b.estimated_start_at from public.bookings b where b.id=v_booking.id;
end; $$;
revoke all on function public.scan_booking_qr(text,text) from public;
grant execute on function public.scan_booking_qr(text,text) to authenticated;

-- Providers' own staff schedule management uses RLS on underlying tables.
-- Never send notifications to unrelated users: matching and dispatch should be done server-side.

alter table public.marketplace_alerts add column if not exists latitude double precision;
alter table public.marketplace_alerts add column if not exists longitude double precision;

create or replace function public.notify_marketplace_alerts()
returns trigger language plpgsql security definer set search_path='' as $$
declare v_alert record; v_label text;
begin
 if new.status <> 'published' then return new; end if;
 if tg_op='UPDATE' and old.status='published' then return new; end if;
 v_label := coalesce(new.title,'New listing');
 for v_alert in
  select a.* from public.marketplace_alerts a
   where a.is_active and a.user_id<>new.owner_id
     and (a.category_key in ('general',new.category_key,new.listing_type) or a.category_key='all')
     and (lower(a.city)=lower(new.city) or (a.latitude is not null and a.longitude is not null and new.latitude is not null and new.longitude is not null and 6371*acos(least(1.0,greatest(-1.0,sin(radians(a.latitude))*sin(radians(new.latitude))+cos(radians(a.latitude))*cos(radians(new.latitude))*cos(radians(new.longitude-a.longitude))))) <= a.radius_km))
     and (a.keywords is null or concat_ws(' ',new.title,new.description,new.city,new.category_key) ilike '%'||a.keywords||'%')
 loop
  insert into public.marketplace_notifications(user_id,alert_id,listing_id,title,body)
  values(v_alert.user_id,v_alert.id,new.id,'Nouvelle annonce / إعلان جديد',v_label||' · '||new.city);
 end loop;
 return new;
end; $$;
drop trigger if exists marketplace_listing_alert_trigger on public.marketplace_listings;
create trigger marketplace_listing_alert_trigger after insert or update of status on public.marketplace_listings for each row execute function public.notify_marketplace_alerts();

create or replace function public.notify_tradesperson_alerts()
returns trigger language plpgsql security definer set search_path='' as $$
declare v_alert record;
begin
 if not new.is_active or not new.verified then return new; end if;
 if tg_op='UPDATE' then
  if old.verified then return new; end if;
 end if;
 for v_alert in select a.* from public.marketplace_alerts a where a.is_active and a.user_id<>new.user_id and a.alert_type='tradesperson' and (a.category_key in ('general',new.trade_key,'all')) and (lower(a.city)=lower(new.city) or (a.latitude is not null and a.longitude is not null and new.latitude is not null and new.longitude is not null and 6371*acos(least(1.0,greatest(-1.0,sin(radians(a.latitude))*sin(radians(new.latitude))+cos(radians(a.latitude))*cos(radians(new.latitude))*cos(radians(new.longitude-a.longitude))))) <= a.radius_km)) loop
  insert into public.marketplace_notifications(user_id,alert_id,tradesperson_id,title,body)
  values(v_alert.user_id,v_alert.id,new.id,'Nouveau professionnel / حرفي جديد',new.display_name||' · '||new.trade_key||' · '||new.city);
 end loop;
 return new;
end; $$;
drop trigger if exists tradesperson_alert_trigger on public.tradespeople_profiles;
create trigger tradesperson_alert_trigger after insert or update of verified on public.tradespeople_profiles for each row execute function public.notify_tradesperson_alerts();
