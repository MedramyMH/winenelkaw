-- Generic classified listings: property rental, car rental, cars, parts, lost items,
-- second-hand goods and other items/services. Public records only expose published rows.
create table if not exists public.marketplace_listings (
 id bigint generated by default as identity primary key,
 owner_id uuid not null references auth.users(id) on delete cascade,
 listing_type text not null check (listing_type in ('sell','rent','wanted','lost_found','service')),
 category_key text not null,
 title text not null check (length(title) between 3 and 140),
 description text not null check (length(description) between 10 and 5000),
 price numeric(12,3), currency char(3) not null default 'TND', price_period text,
 city text not null, address_label text, latitude double precision, longitude double precision,
 contact_phone text, images text[] not null default '{}',
 status text not null default 'pending' check (status in ('pending','published','rejected','sold','rented','closed')),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 expires_at timestamptz default (now()+interval '90 days'),
 check (price is null or price >= 0),
 check (latitude is null or latitude between -90 and 90),
 check (longitude is null or longitude between -180 and 180)
);
create index if not exists marketplace_listings_public_idx on public.marketplace_listings(status,category_key,created_at desc);
create index if not exists marketplace_listings_location_idx on public.marketplace_listings(city,category_key,status);

-- Skilled trades directory; verification is performed by moderators, never self-asserted.
create table if not exists public.tradespeople_profiles (
 id bigint generated by default as identity primary key,
 user_id uuid not null unique references auth.users(id) on delete cascade,
 display_name text not null,
 trade_key text not null,
 bio text,
 phone text,
 city text not null,
 address_label text,
 latitude double precision, longitude double precision,
 years_experience integer not null default 0 check (years_experience between 0 and 80),
 hourly_rate numeric(10,3), rating numeric(2,1) not null default 0 check (rating between 0 and 5),
 review_count integer not null default 0,
 verified boolean not null default false,
 is_active boolean not null default true,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists tradespeople_search_idx on public.tradespeople_profiles(trade_key,city,is_active,verified);

create table if not exists public.marketplace_alerts (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 alert_type text not null check (alert_type in ('listing','tradesperson','service_request')),
 category_key text not null,
 city text not null,
