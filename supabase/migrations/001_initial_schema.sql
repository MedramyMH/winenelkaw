-- Win Nalkaw initial schema. Apply to a fresh Supabase project.
create extension if not exists pgcrypto;
create extension if not exists postgis;

create type public.app_role as enum ('customer','provider','admin');
create type public.booking_status as enum ('pending','confirmed','cancelled','completed','rejected','no_show');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  preferred_language text not null default 'ar' check (preferred_language in ('ar','fr')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.user_roles (
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.app_role not null default 'customer',
  created_at timestamptz not null default now(),
  primary key(user_id, role)
);
create table public.businesses (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete restrict,
  name_ar text not null,
  name_fr text,
  description_ar text,
  description_fr text,
  category_key text not null,
  address_ar text,
  address_fr text,
  city text not null default 'Tunis',
  location geography(point,4326),
  phone text,
  cover_url text,
  logo_url text,
  verified boolean not null default false,
  is_active boolean not null default false,
  accepts_online_booking boolean not null default false,
  timezone text not null default 'Africa/Tunis',
  cancellation_hours integer not null default 12 check(cancellation_hours >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index businesses_location_gix on public.businesses using gist(location);
create index businesses_category_idx on public.businesses(category_key,is_active);

create table public.business_members (
  business_id bigint not null references public.businesses(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  member_role text not null default 'staff' check(member_role in ('manager','staff')),
  created_at timestamptz not null default now(),
  primary key(business_id,user_id)
);
create table public.services (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses(id) on delete cascade,
  name_ar text not null,
  name_fr text,
  description_ar text,
  description_fr text,
  duration_minutes integer not null check(duration_minutes between 5 and 1440),
  buffer_minutes integer not null default 0 check(buffer_minutes between 0 and 240),
  price numeric(10,3) check(price is null or price >= 0),
  currency char(3) not null default 'TND',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create index services_business_idx on public.services(business_id,is_active);

create table public.staff_profiles (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  display_name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create table public.service_staff (
  service_id bigint not null references public.services(id) on delete cascade,
  staff_id bigint not null references public.staff_profiles(id) on delete cascade,
  primary key(service_id,staff_id)
);
create table public.business_hours (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses(id) on delete cascade,
  weekday smallint not null check(weekday between 0 and 6),
  opens_at time,
  closes_at time,
  is_closed boolean not null default false,
  check(is_closed or (opens_at is not null and closes_at is not null and opens_at < closes_at)),
  unique(business_id,weekday)
);
create table public.staff_availability (
  id bigint generated by default as identity primary key,
  staff_id bigint not null references public.staff_profiles(id) on delete cascade,
  weekday smallint not null check(weekday between 0 and 6),
  starts_at time not null,
  ends_at time not null,
  check(starts_at < ends_at)
);
create table public.staff_breaks (
  id bigint generated by default as identity primary key,
  staff_id bigint not null references public.staff_profiles(id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  label text,
  check(starts_at < ends_at)
);
create table public.business_closures (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses(id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  reason text,
  check(starts_at < ends_at)
);

create table public.bookings (
  id bigint generated by default as identity primary key,
  booking_reference text not null unique default ('WN-' || upper(substr(encode(gen_random_bytes(8),'hex'),1,10))),
  customer_id uuid not null references auth.users(id) on delete restrict,
  business_id bigint not null references public.businesses(id) on delete restrict,
  staff_id bigint references public.staff_profiles(id) on delete set null,
  customer_name text not null,
  customer_phone text not null,
  booking_date date not null,
  start_time time not null,
  end_time time not null,
  timezone text not null default 'Africa/Tunis',
  status public.booking_status not null default 'pending',
  customer_note text,
  cancellation_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check(start_time < end_time)
);
create index bookings_customer_idx on public.bookings(customer_id,booking_date desc);
create index bookings_business_idx on public.bookings(business_id,booking_date,start_time);
create index bookings_staff_schedule_idx on public.bookings(staff_id,booking_date,start_time,end_time) where status in ('pending','confirmed');
create table public.booking_items (
  id bigint generated by default as identity primary key,
  booking_id bigint not null references public.bookings(id) on delete cascade,
  service_id bigint references public.services(id) on delete set null,
